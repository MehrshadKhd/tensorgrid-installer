'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const installerRoot = path.resolve(__dirname, '..');
const rendererRoot = path.join(installerRoot, 'renderer');
const assetRoot = path.join(rendererRoot, 'assets');
const fontRoot = path.join(assetRoot, 'fonts');
const sourceAssetRoot = path.join(installerRoot, 'source-assets');
const sourceFontRoot = path.join(sourceAssetRoot, 'fonts');
const resourcesRoot = path.join(installerRoot, 'resources');
const portableBrandRoot = path.join(sourceAssetRoot, 'brand');

function resolveRepoRoot() {
    const candidates = [
        path.resolve(installerRoot, '..', 'TensorGrid'),
        path.resolve(installerRoot, '..'),
        path.resolve(installerRoot, '..', '..')
    ];
    return candidates.find(candidate => fs.existsSync(path.join(candidate, 'frontend', 'public', 'icons', 'icon.svg')))
        || candidates[candidates.length - 1];
}

const repoRoot = resolveRepoRoot();

function ensureDirectory(directory) {
    fs.mkdirSync(directory, { recursive: true });
}

function resolveTokenImports(filePath, seen = new Set()) {
    const absolutePath = path.resolve(filePath);
    if (seen.has(absolutePath)) {
        throw new Error(`Circular design token import: ${absolutePath}`);
    }
    seen.add(absolutePath);

    const source = fs.readFileSync(absolutePath, 'utf8');
    const directory = path.dirname(absolutePath);
    const resolved = source.replace(/@import\s+(['"])([^'"]+)\1\s*;?/g, (_match, _quote, importPath) => {
        const importedPath = path.resolve(directory, importPath);
        return `/* inlined from ${path.relative(repoRoot, importedPath).replaceAll('\\', '/')} */\n${resolveTokenImports(importedPath, new Set(seen))}`;
    });

    return resolved;
}

function copyAsset(source, target) {
    ensureDirectory(path.dirname(target));
    fs.copyFileSync(source, target);
}

function copyFonts() {
    if (!fs.existsSync(sourceFontRoot)) {
        throw new Error(`Missing bundled font source directory: ${sourceFontRoot}`);
    }

    const fontFiles = fs.readdirSync(sourceFontRoot)
        .filter(fileName => /\.(ttf|otf|woff2)$/i.test(fileName))
        .sort();
    if (fontFiles.length === 0) {
        throw new Error(`No bundled font files found in ${sourceFontRoot}`);
    }

    fontFiles.forEach(fileName => {
        copyAsset(path.join(sourceFontRoot, fileName), path.join(fontRoot, fileName));
    });
    if (fs.existsSync(path.join(sourceFontRoot, 'OFL.txt'))) {
        copyAsset(path.join(sourceFontRoot, 'OFL.txt'), path.join(fontRoot, 'OFL.txt'));
    }
}

function resolveAssetSource(monorepoPath, portablePath) {
    return fs.existsSync(monorepoPath) ? monorepoPath : portablePath;
}

function writeWindowsIcon() {
    const inputPath = resolveAssetSource(
        path.join(repoRoot, 'frontend', 'public', 'icons', 'android', 'launchericon-512x512.png'),
        path.join(portableBrandRoot, 'tensorgrid-mark-512.png')
    );
    const scriptPath = path.join(__dirname, 'create-windows-icon.ps1');
    const powershell = process.platform === 'win32' ? 'powershell.exe' : 'pwsh';
    const result = spawnSync(powershell, [
        '-NoProfile',
        '-NonInteractive',
        '-ExecutionPolicy',
        'Bypass',
        '-File',
        scriptPath,
        '-InputPath',
        inputPath,
        '-OutputPath',
        path.join(resourcesRoot, 'icon.ico')
    ], { stdio: 'inherit' });
    if (result.error) {
        throw result.error;
    }
    if (result.status !== 0) {
        throw new Error(`Windows icon generation failed with exit code ${result.status}`);
    }
}

function syncDesignAssets() {
    ensureDirectory(assetRoot);
    ensureDirectory(fontRoot);
    ensureDirectory(resourcesRoot);
    copyFonts();

    const tokenSource = resolveAssetSource(
        path.join(repoRoot, 'frontend', 'src', 'app', 'shared', 'ui', 'styles', 'tokens.css'),
        path.join(sourceAssetRoot, 'tokens.css')
    );
    const tokenTarget = path.join(rendererRoot, 'tokens.css');
    const tokenContent = [
        '/* Generated by scripts/sync-design-assets.cjs. Do not edit manually. */',
        `/* Source: ${path.relative(repoRoot, tokenSource).replaceAll('\\', '/')} */`,
        resolveTokenImports(tokenSource)
    ].join('\n\n');
    fs.writeFileSync(tokenTarget, `${tokenContent}\n`, 'utf8');

    copyAsset(
        resolveAssetSource(
            path.join(repoRoot, 'frontend', 'public', 'icons', 'icon.svg'),
            path.join(portableBrandRoot, 'tensorgrid-mark.svg')
        ),
        path.join(assetRoot, 'tensorgrid-mark.svg')
    );
    copyAsset(
        resolveAssetSource(
            path.join(repoRoot, 'frontend', 'public', 'icons', 'android', 'launchericon-512x512.png'),
            path.join(portableBrandRoot, 'tensorgrid-mark-512.png')
        ),
        path.join(assetRoot, 'tensorgrid-mark-512.png')
    );
    writeWindowsIcon();
}

syncDesignAssets();
